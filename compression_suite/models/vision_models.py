@register_model("fast_convnet_teacher")
def build_fast_convnet_teacher(num_classes: int = 10, **kwargs) -> FastConvNetTeacher:
    return FastConvNetTeacher(num_classes=num_classes)


@register_model("fast_convnet_student")
def build_fast_convnet_student(num_classes: int = 10, **kwargs) -> FastConvNetStudent:
    return FastConvNetStudent(num_classes=num_classes)


@register_model("resnet18")
def build_resnet18(num_classes: int = 10, **kwargs) -> ResNetBase:
    return ResNetBase(BasicBlock, [2, 2, 2, 2], num_classes=num_classes)


@register_model("resnet34")
def build_resnet34(num_classes: int = 10, **kwargs) -> ResNetBase:
    return ResNetBase(BasicBlock, [3, 4, 6, 3], num_classes=num_classes)


@register_model("resnet50")
def build_resnet50(num_classes: int = 10, **kwargs) -> ResNetBase:
    return ResNetBase(Bottleneck, [3, 4, 6, 3], num_classes=num_classes)
